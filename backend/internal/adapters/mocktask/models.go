package mocktask

import (
	"context"
	"encoding/json"
	"fmt"

	"github.com/leungll/Emberling/backend/internal/domain"
	"github.com/leungll/Emberling/backend/internal/registry"
)

// taskModelConfigSchema accepts only an empty object: a task model's per-call settings
// come from the image_generation node's own config.
const taskModelConfigSchema = `{"type": "object", "additionalProperties": false}`

// TaskModel is one image model a task Provider serves.
type TaskModel struct {
	ID          string
	DisplayName string
	Description string
}

// TaskModels declares the image models served by one asynchronous task Provider, such as
// the task gateway, so the Model Registry can resolve each to that Provider's ID. It
// registers models only: their images are generated by dispatching tasks through the
// image_generation node, so Generate always refuses.
type TaskModels struct {
	providerID string
	models     []TaskModel
}

var _ registry.ModelProvider = (*TaskModels)(nil)

// NewTaskModels returns the declaration of models served by providerID.
func NewTaskModels(providerID string, models []TaskModel) *TaskModels {
	return &TaskModels{providerID: providerID, models: append([]TaskModel(nil), models...)}
}

// Models returns one image_generation registration per model, each naming the Provider.
func (m *TaskModels) Models(context.Context) ([]registry.ModelRegistration, error) {
	registrations := make([]registry.ModelRegistration, 0, len(m.models))
	for _, model := range m.models {
		registrations = append(registrations, registry.ModelRegistration{ModelMetadata: domain.ModelMetadata{
			ID:           model.ID,
			DisplayName:  model.DisplayName,
			Description:  model.Description,
			Capabilities: []string{domain.ModelCapabilityImageGeneration},
			ConfigSchema: json.RawMessage(taskModelConfigSchema),
			ProviderID:   m.providerID,
		}})
	}
	return registrations, nil
}

// Generate refuses every decision request: these models answer only through tasks.
func (m *TaskModels) Generate(context.Context, registry.ModelRequest) (registry.ModelResponse, error) {
	return registry.ModelResponse{}, fmt.Errorf("mocktask: models served by provider %q answer only image generation tasks", m.providerID)
}
